// Command levelbank pre-generates brick layouts with the game's own level
// generator and writes them as Luau modules for the Roblox port, so the
// Roblox chambers are the Steam chambers, not a look-alike.
//
//	go run ./tools/levelbank -out ../roblox-levels
//
// Each act gets one module with depthsPerAct x seedsPerDepth layouts. A
// layout is one string, five characters per cell, row by row:
//
//	kind (a = Empty .. p = Elite), HP (0-9), palette colour (0-5),
//	stack height (0-9), cap kind (a .. p)
//
// The pacing (chamberBudget, pacedLevel) is copied from play.go so boards
// have the same amount of work as on Steam; keep the two in step.
package main

import (
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"

	"orb/levelgen"
)

const (
	acts          = 3
	depthsPerAct  = 8
	seedsPerDepth = 12
	denseBudget   = 6.0
)

func chamberBudget(p levelgen.Params) float64 {
	u := denseBudget * (9.5 + 5.6*float64(min(p.Depth, 26))) * (1 + 0.12*float64(p.Act-1))
	if p.Elite {
		u *= 1.3
	}
	return u
}

func levelUnits(d *levelgen.Level) float64 {
	u := 0.0
	for _, row := range d.Cells {
		for _, c := range row {
			if c.Kind.Required() {
				u += float64(max(1, c.HP) * max(1, c.Stack))
			}
		}
	}
	return u
}

func pacedLevel(p levelgen.Params) *levelgen.Level {
	want := chamberBudget(p)
	var best *levelgen.Level
	bestD := math.Inf(1)
	for k := 0; k < 8; k++ {
		q := p
		q.Seed = p.Seed + int64(k)*7919
		d := levelgen.Generate(q)
		u := levelUnits(d)
		cells := float64(d.Count(func(c levelgen.Cell) bool { return c.Kind != levelgen.Empty }))
		dist := math.Abs(math.Log(u/want)) - 0.35*cells/float64(levelgen.MaxRows*levelgen.Cols)
		if dist < bestD {
			best, bestD = d, dist
		}
		if u > want*0.7 && u < want*1.3 {
			break
		}
	}
	if u := levelUnits(best); u > want*1.4 {
		k := want * 1.25 / u
		for r := range best.Cells {
			for c := range best.Cells[r] {
				cl := &best.Cells[r][c]
				if !cl.Kind.Required() {
					continue
				}
				cl.HP = max(1, int(math.Round(float64(cl.HP)*math.Sqrt(k))))
				if cl.Stack > 1 {
					cl.Stack = max(1, int(math.Round(float64(cl.Stack)*math.Sqrt(k))))
				}
			}
		}
	}
	return best
}

func digit(n int) byte { return byte('0' + max(0, min(9, n))) }

func encode(d *levelgen.Level) string {
	var b strings.Builder
	for r := 0; r < levelgen.MaxRows; r++ {
		for c := 0; c < levelgen.Cols; c++ {
			cl := d.Cells[r][c]
			if d.Outside[r][c] {
				cl = levelgen.Cell{}
			}
			b.WriteByte(byte('a' + int(cl.Kind)))
			b.WriteByte(digit(cl.HP))
			b.WriteByte(digit(cl.Color))
			b.WriteByte(digit(cl.Stack))
			b.WriteByte(byte('a' + int(cl.Cap)))
		}
	}
	return b.String()
}

func main() {
	out := flag.String("out", "roblox-levels", "output folder")
	flag.Parse()
	if err := os.MkdirAll(*out, 0o755); err != nil {
		panic(err)
	}
	for act := 1; act <= acts; act++ {
		var b strings.Builder
		fmt.Fprintf(&b, "--!strict\n-- LevelBank/Act%d.luau: brick layouts made by the game's own generator.\n", act)
		b.WriteString("-- GENERATED by tools/levelbank (Go). Do not edit: re-run the tool.\n")
		fmt.Fprintf(&b, "-- %d columns x %d rows, 5 characters per cell: kind, HP, colour, stack, cap.\n\n", levelgen.Cols, levelgen.MaxRows)
		b.WriteString("return {\n")
		for depth := 1; depth <= depthsPerAct; depth++ {
			fmt.Fprintf(&b, "\t[%d] = {\n", depth)
			for s := 0; s < seedsPerDepth; s++ {
				seed := levelgen.Mix(int64(act), int64(depth), int64(s), 0x0b10c5)
				elite := s%4 == 3
				p := levelgen.Params{Seed: seed, Depth: (act-1)*depthsPerAct + depth, Act: act, Elite: elite}
				d := pacedLevel(p)
				fmt.Fprintf(&b, "\t\t{ name = %q, shape = %d, layerShift = %d, elite = %v, crystals = %v,\n\t\t  cells = %q },\n",
					d.Name, d.Shape, d.LayerShift, elite, d.Objective == levelgen.ObjCrystals, encode(d))
			}
			b.WriteString("\t},\n")
		}
		b.WriteString("}\n")
		p := filepath.Join(*out, fmt.Sprintf("Act%d.luau", act))
		if err := os.WriteFile(p, []byte(b.String()), 0o644); err != nil {
			panic(err)
		}
		fmt.Println("wrote", p)
	}
	// the arena wall shapes
	var b strings.Builder
	b.WriteString("--!strict\n-- LevelBank/Arenas.luau: arena wall polylines (x, z), near-left corner round to near-right.\n-- GENERATED by tools/levelbank (Go). Do not edit: re-run the tool.\n\nreturn {\n")
	for s := 0; s < levelgen.NumShapes; s++ {
		fmt.Fprintf(&b, "\t[%d] = { name = %q, pts = {", s, levelgen.ShapeNames[s])
		for i, pt := range levelgen.Arena(s) {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{%.4g, %.4g}", pt.X, pt.Z)
		}
		b.WriteString("} },\n")
	}
	b.WriteString("}\n")
	p := filepath.Join(*out, "Arenas.luau")
	if err := os.WriteFile(p, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote", p)
}
